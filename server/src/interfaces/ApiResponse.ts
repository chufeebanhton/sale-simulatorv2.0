export interface ApiError {
    status: "error";
    message: string;
    error: {
        code: string;
        details?: unknown;
    };
    meta: {
        timestamp: string;
    };
}

export interface ApiSuccess<T> {
    status: "success";
    message: string;
    data: T;
    meta: {
        timestamp: string;
    };
}